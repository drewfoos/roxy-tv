-- Sidecar subtitle languages as ISO 639-2 codes, as ffprobe gives embedded tracks and as
-- the scanner now writes them ("en" -> "eng"), so existing tracks match new ones without
-- re-ingesting every video. Only external tracks; "hi" is not touched (the parser reads it
-- as hearing impaired, never as a language).
UPDATE media_streams SET language = CASE lower(language)
    WHEN 'en' THEN 'eng'
    WHEN 'ja' THEN 'jpn'
    WHEN 'es' THEN 'spa'
    WHEN 'pt' THEN 'por'
    WHEN 'fr' THEN 'fra'
    WHEN 'fre' THEN 'fra'
    WHEN 'de' THEN 'deu'
    WHEN 'ger' THEN 'deu'
    WHEN 'it' THEN 'ita'
    WHEN 'ru' THEN 'rus'
    WHEN 'zh' THEN 'zho'
    WHEN 'chi' THEN 'zho'
    WHEN 'ko' THEN 'kor'
    WHEN 'ar' THEN 'ara'
    WHEN 'nl' THEN 'nld'
    WHEN 'dut' THEN 'nld'
    WHEN 'pl' THEN 'pol'
    WHEN 'sv' THEN 'swe'
    WHEN 'no' THEN 'nor'
    WHEN 'nb' THEN 'nor'
    WHEN 'da' THEN 'dan'
    WHEN 'fi' THEN 'fin'
    WHEN 'tr' THEN 'tur'
    WHEN 'cs' THEN 'ces'
    WHEN 'cze' THEN 'ces'
    WHEN 'hu' THEN 'hun'
    WHEN 'el' THEN 'ell'
    WHEN 'gre' THEN 'ell'
    WHEN 'he' THEN 'heb'
    WHEN 'th' THEN 'tha'
    WHEN 'vi' THEN 'vie'
    WHEN 'id' THEN 'ind'
    WHEN 'ms' THEN 'msa'
    WHEN 'uk' THEN 'ukr'
    WHEN 'ro' THEN 'ron'
    WHEN 'rum' THEN 'ron'
    WHEN 'bg' THEN 'bul'
    WHEN 'hr' THEN 'hrv'
    WHEN 'sr' THEN 'srp'
    WHEN 'sk' THEN 'slk'
    WHEN 'slo' THEN 'slk'
    WHEN 'fa' THEN 'fas'
    WHEN 'per' THEN 'fas'
    WHEN 'ca' THEN 'cat'
    ELSE language END
WHERE is_external = 1 AND language IS NOT NULL;
